let currentLang = 'zh-CN';

export function resolveLang(pref) {
  if (pref === 'en') return 'en';
  if (pref === 'zh-CN' || pref === 'zh') return 'zh-CN';
  const nav = (globalThis.navigator?.language || '').toLowerCase();
  return nav.startsWith('zh') ? 'zh-CN' : 'en';
}

export function getLang() { return currentLang; }
export function setLang(l) {
  currentLang = resolveLang(l);
  if (typeof document !== 'undefined') document.documentElement.lang = currentLang;
  return currentLang;
}

export function t(key, ...args) {
  const table = DICT[currentLang] || DICT['zh-CN'];
  const val = table[key] ?? DICT['zh-CN'][key] ?? key;
  return typeof val === 'function' ? val(...args) : val;
}

export function relTime(ts, lang = currentLang) {
  const d = Math.max(0, (Date.now() - ts) / 1000);
  const isEn = lang === 'en';
  if (d < 60) return isEn ? 'Just now' : '刚刚';
  if (d < 3600) return isEn ? `${Math.floor(d / 60)}m ago` : `${Math.floor(d / 60)} 分钟前`;
  if (d < 86400) return isEn ? `${Math.floor(d / 3600)}h ago` : `${Math.floor(d / 3600)} 小时前`;
  if (d < 86400 * 7) return isEn ? `${Math.floor(d / 86400)}d ago` : `${Math.floor(d / 86400)} 天前`;
  return new Date(ts).toLocaleDateString(isEn ? 'en-US' : 'zh-CN');
}

